// The written docs at https://dshakes.github.io/onpar/docs/, generated from the
// repo's Markdown by scripts/sync-docs.mjs. The landing page, generated assets and
// the interactive lab are plain static files copied in by scripts/postbuild.mjs.
// The build fails on any broken internal link (starlight-links-validator).
// React renders the interactive diagrams in src/components/diagrams/.
import { defineConfig } from 'astro/config';
import react from '@astrojs/react';
import starlight from '@astrojs/starlight';
import starlightLinksValidator from 'starlight-links-validator';

// Sidebar groups for the guide sections that exist in docs/guide/ (a group for an
// empty directory fails Starlight's config hook). Labels in reading order.
import { existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const GUIDE = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'guide');
const GUIDE_LABELS = [
	['start', 'Start here'],
	['loop', 'The loop'],
	['agents', 'For agents'],
	['learn', 'Learn'],
	['reference', 'Reference'],
];
function guideGroups() {
	return GUIDE_LABELS.filter(([dir]) => existsSync(join(GUIDE, dir)) && readdirSync(join(GUIDE, dir)).some((f) => f.endsWith('.md'))).map(
		([dir, label]) => ({ label, items: [{ autogenerate: { directory: `docs/${dir}` } }] }),
	);
}

export default defineConfig({
	site: 'https://dshakes.github.io',
	base: '/onpar',
	trailingSlash: 'always',
	integrations: [
		react(),
		starlight({
			title: 'onpar',
			description: 'Prove which open-weight LLM can replace your closed-model API, on your own traffic, hardware and budget.',
			// Brand files are generated by tools/brand.py into assets/brand/.
			logo: {
				light: './assets/brand/lockup-horizontal.svg',
				dark: './assets/brand/lockup-horizontal-on-dark.svg',
				alt: 'onpar',
				replacesTitle: true,
			},
			favicon: '/favicon.svg',
			customCss: ['./src/styles/onpar.css'],
			social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/dshakes/onpar' }],
			editLink: { baseUrl: 'https://github.com/dshakes/onpar/edit/main/' },
			head: [
				// Dark-first, like the landing page: default to dark until the reader picks a theme.
				{
					tag: 'script',
					content: "try{if(!localStorage.getItem('starlight-theme'))localStorage.setItem('starlight-theme','dark')}catch(e){}",
				},
			],
			plugins: [
				starlightLinksValidator({
					// `http://127.0.0.1:8000/v1` in a help string is an example endpoint, not a link.
					errorOnLocalLinks: false,
					// ponytail: these are copied into dist after the build, so the validator
					// cannot see them. sync-docs.mjs checks every /onpar/assets/ target exists.
					exclude: ['/onpar/', '/onpar/assets/**', '/onpar/lab/', '/onpar/lab/**'],
				}),
			],
			sidebar: [
				{ label: 'Overview', slug: 'docs' },
				// The reader's path, in the order the loop runs. Pages come from
				// docs/guide/<section>/NN-name.md; NN orders them (scripts/sync-docs.mjs).
				...guideGroups(),
				{ label: 'Decisions', collapsed: true, items: [{ autogenerate: { directory: 'docs/adr' } }] },
				// The specs that built the product: history and intent, out of the reader's path.
				{
					label: 'Project',
					collapsed: true,
					items: ['00-verdict', '05-field-guide', '10-landscape', '20-prd', '30-architecture', '40-ux', '50-roadmap', '60-pitch', '70-naming', '80-implementation-plan', '90-ci-gating', '95-ga-readiness'].map((s) => ({ slug: `docs/${s}` })),
				},
				// Starlight prefixes `base` onto internal sidebar links itself.
				{ label: 'Landing page', link: '/' },
				{ label: 'Interactive lab', link: '/lab/' },
			],
		}),
	],
});
